#!/usr/bin/env bash
# M7b: the Remotion textures for the Blender screens, as image sequences that blender/look.py maps onto the screens
# (production log 37+):
#   M7-O04-PhoneScreen        O04's phone, legible at 1080p (human interventions 18): PNG, 720x1560, 143 frames
#   M7-Tree-<screen>-night    O08c's night cutaway (72 frames)  } the treehouse's incident-night screens (human
#   M7-Tree-<screen>-day      the O18 bridge (576 frames)        } interventions 19): JPEG q95, laptops 1280x800,
#                                                                   phones 540x1170 (the ringing phone 720x1560)
# plus the #it-help thread (O08's, IT's reply in) as a still for the third treehouse phone.
# Out: assets/gen/tex/m7b/<composition>/frames/<n>.<ext> (frame sequences: out of the manifest, regenerated by this
# script) and assets/gen/tex/m7b/it_help_o08.png. Same render flags as scripts/m5_remotion.sh (CPU, --gl=swangle,
# concurrency 2).
# Usage: scripts/m7b_remotion.sh [composition-id ...]   (no args: all)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
out=assets/gen/tex/m7b
mkdir -p "$out"
quiet() { grep -v -i -e zod -e "version mismatch" -e "^-*$" -e "wrong versions" -e "breakages" -e "React context" -e "Type errors" \
  -e "Failed renders" -e "resolve:" -e "package.json has" -e "Remove the" -e "Run .npx" -e "^$" || true; }
SEL=("$@")
want() { [ ${#SEL[@]} -eq 0 ] || [[ " ${SEL[*]} " =~ " $1 " ]]; }
seq_() {  # id scale format
  want "$1" || return 0
  t=$(date +%s)
  mkdir -p "$out/$1/frames"
  extra=()
  [ "$3" = jpeg ] && extra=(--jpeg-quality=95)
  npx remotion render "$1" "$out/$1/frames" --sequence --image-sequence-pattern="[frame].[ext]" --image-format="$3" "${extra[@]}" \
    --scale="$2" --gl=swangle --concurrency=2 --log=error 2>&1 | quiet
  echo "$1: $(ls "$out/$1/frames" | wc -l) frames, $(( $(date +%s) - t )) s"
}
seq_ M7-O04-PhoneScreen 0.6666667 png
for v in night day; do
  seq_ "M7-Tree-TwoFactor-$v" 0.5 jpeg
  seq_ "M7-Tree-AlertCall-$v" 0.6666667 jpeg
  for s in Dashboard Terminal Agent VideoCall; do seq_ "M7-Tree-$s-$v" 1 jpeg; done
done
if want it_help_o08; then
  npx remotion still O08-PhoneChatScreen "$out/it_help_o08.png" --frame=40 --scale=0.5 --gl=swangle --log=error 2>&1 | quiet
  echo "it_help_o08.png"
fi
